export function findDemoSandboxByEmail(email: string): DemoSandboxAccount | null {
  const normalizedEmail = email.trim().toLowerCase();
  if (!normalizedEmail) return null;
  return (
    DEMO_SANDBOX_ACCOUNTS.find((acc) => acc.email.toLowerCase() === normalizedEmail) || null
  );
}

export function matchDemoSandboxCredentials(
  email: string,
  password: string
): DemoSandboxAccount | null {
  const normalizedEmail = email.trim().toLowerCase();
  const normalizedPassword = password.trim();
  return (
    DEMO_SANDBOX_ACCOUNTS.find(
      (acc) => acc.email.toLowerCase() === normalizedEmail && acc.password === normalizedPassword
    ) || null
  );
}
